import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";

const root = fileURLToPath(new URL("..", import.meta.url));
const destination = new URL(
  "../lib/malatya-category-c-generated.ts",
  import.meta.url,
);
const vite = await createServer({
  appType: "custom",
  configFile: false,
  logLevel: "silent",
  root,
  resolve: { alias: { "@": root } },
  server: { hmr: false, middlewareMode: true },
});

try {
  const { computeMalatyaCategoryCRoundAudit } = await vite.ssrLoadModule(
    "/lib/malatya-category-c-all-rounds.ts",
  );
  const rounds = [];
  for (let round = 1; round <= 9; round += 1) {
    const audit = computeMalatyaCategoryCRoundAudit(round);
    rounds.push({ round, pairings: audit.generated });
  }

  const contents = [
    "// Generated by scripts/generate-benchmark-cache.mjs. Do not edit by hand.",
    "export const MALATYA_C_GENERATED_ROUNDS =",
    `${JSON.stringify(rounds, null, 2)} as const;`,
    "",
  ].join("\n");

  await writeFile(destination, contents, "utf8");
  process.stdout.write(`Updated ${fileURLToPath(destination)}\n`);
} finally {
  await vite.close();
}
