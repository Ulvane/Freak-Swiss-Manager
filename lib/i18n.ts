const patternTranslations: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
  [/^(\d+) players?$/, (m) => `${m[1]} oyuncu`],
  [/^(\d+) guests?$/, (m) => `${m[1]} konuk`],
  [/^(\d+) moderators?$/, (m) => `${m[1]} moderatör`],
  [/^Round (\d+)(?:\/(\d+))?$/, (m) => `Tur ${m[1]}${m[2] ? `/${m[2]}` : ""}`],
  [/^ROUND (\d+) VERDICT \/ (.+)$/, (m) => `TUR ${m[1]} KARARI / ${m[2]}`],
  [/^([A-Z]+) · (.+)$/, (m) => `${m[1]} · ${m[2]}`],
  [/^Delete (\d+) selected$/, (m) => `${m[1]} seçileni sil`],
  [/^(\d+) token\(s\) recorded$/, (m) => `${m[1]} jeton kaydedildi`],
  [/^Round (\d+) source$/, (m) => `${m[1]}. tur kaynağı`],
  [/^(\d+) of (\d+) official matchups are reproduced\.$/, (m) => `${m[1]} / ${m[2]} resmî eşleşme yeniden oluşturuldu.`],
  [/^(\d+) allocations$/, (m) => `${m[1]} eşleşme`],
];

function preserveWhitespace(source: string, translated: string) {
  const leading = source.match(/^\s*/)?.[0] ?? "";
  const trailing = source.match(/\s*$/)?.[0] ?? "";
  return `${leading}${translated.trim()}${trailing}`;
}

export function translateText(source: string, language: Language): string {
  if (language === "en") return source;
  const normalized = source.trim().replace(/\s+/g, " ");
  const exact = exactTranslations[normalized];
  if (exact) return preserveWhitespace(source, exact);
  for (const [pattern, translate] of patternTranslations) {
    const match = normalized.match(pattern);
    if (match) return preserveWhitespace(source, translate(match));
  }
  return source;
}

export function readLanguage(): Language {
  if (typeof window === "undefined") return "en";
  return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === "tr" ? "tr" : "en";
}
