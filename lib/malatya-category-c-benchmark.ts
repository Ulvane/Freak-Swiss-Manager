function playerId(seed: number) {
  return `seed-${seed}`;
}

function seedFromPlayerId(id: string | null) {
  return id ? Number(id.replace("seed-", "")) : null;
}

function pairingKey(whiteSeed: number, blackSeed: number | null) {
  if (blackSeed === null) return `bye:${whiteSeed}`;
  return [whiteSeed, blackSeed].sort((a, b) => a - b).join(":");
}

export function createMalatyaCategoryCRoundOneAudit() {
  const generateFor = (players: BenchmarkPlayer[]) =>
    createSwissPairings(
      hydratePairingPlayers(
        players.map((player) => ({
          id: playerId(player.seed),
          name: player.name,
          rating: player.rating,
          seed: player.seed,
        })),
        [],
      ),
    ).map((pairing, index) => ({
      board: index + 1,
      whiteSeed: seedFromPlayerId(pairing.whitePlayerId)!,
      blackSeed: seedFromPlayerId(pairing.blackPlayerId),
    }));

  const auditGenerated = (
    generated: Array<{
      board: number;
      whiteSeed: number;
      blackSeed: number | null;
    }>,
  ) => {
    const generatedByKey = new Map(
      generated.map((pairing) => [
        pairingKey(pairing.whiteSeed, pairing.blackSeed),
        pairing,
      ]),
    );

    const rows = MALATYA_C_ROUND_ONE.map((official, index) => {
      const sameBoard = generated[index];
      const matchup = generatedByKey.get(
        pairingKey(official.whiteSeed, official.blackSeed),
      );
      const sameBoardOpponents =
        pairingKey(sameBoard.whiteSeed, sameBoard.blackSeed) ===
        pairingKey(official.whiteSeed, official.blackSeed);
      const exactColors =
        sameBoard.whiteSeed === official.whiteSeed &&
        sameBoard.blackSeed === official.blackSeed;

      const status = exactColors
        ? "exact"
        : sameBoardOpponents
          ? "colors-reversed"
          : matchup
            ? "different-board"
            : "different-matchup";

      return { official, generated: sameBoard, matchup, status } as const;
    });

    return {
      generated,
      rows,
      stats: {
        exactBoardAndColors: rows.filter((row) => row.status === "exact").length,
        sameOpponentsSameBoard: rows.filter(
          (row) => row.status === "exact" || row.status === "colors-reversed",
        ).length,
        sameMatchupAnywhere: rows.filter((row) => row.matchup).length,
        differentMatchups: rows.filter((row) => !row.matchup).length,
      },
    };
  };

  const raw = auditGenerated(generateFor(MALATYA_C_PLAYERS));
  const officialByeSeed = MALATYA_C_ROUND_ONE.find(
    (pairing) => pairing.blackSeed === null,
  )!.whiteSeed;
  const controlledGenerated = generateFor(
    MALATYA_C_PLAYERS.filter((player) => player.seed !== officialByeSeed),
  );
  controlledGenerated.push({
    board: MALATYA_C_ROUND_ONE.length,
    whiteSeed: officialByeSeed,
    blackSeed: null,
  });
  const controlled = auditGenerated(controlledGenerated);

  return {
    activePlayerCount: MALATYA_C_PLAYERS.length,
    officialByeSeed,
    generated: controlled.generated,
    rows: controlled.rows,
    stats: controlled.stats,
    rawStats: raw.stats,
  };
}

export function categoryCPlayer(seed: number | null) {
  return seed === null
    ? null
    : MALATYA_C_PLAYERS.find((player) => player.seed === seed) ?? null;
}
